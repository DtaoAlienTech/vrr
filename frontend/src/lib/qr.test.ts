const rowsOf = (matrix: boolean[][]) => matrix.map((row) => row.map((dark) => (dark ? "1" : "0")).join(""));

test("matches the reference implementation module by module", () => {
  for (const vector of REFERENCE) {
    const matrix = encodeQr(vector.text, { mask: vector.mask });
    assert.equal(matrix.length, vector.version * 4 + 17, `size of "${vector.text.slice(0, 20)}"`);
    assert.deepEqual(rowsOf(matrix), vector.rows, `"${vector.text.slice(0, 20)}"`);
  }
});

test("the size grows with the text and the smallest version is used", () => {
  assert.equal(versionFor(1), 1);
  assert.equal(versionFor(14), 1);
  assert.equal(versionFor(15), 2);
  assert.equal(encodeQr("hello world").length, 21);
});

test("the byte capacities are the ones of the QR standard (level M)", () => {
  const known: Record<number, number> = { 1: 14, 2: 26, 3: 42, 4: 62, 5: 84, 6: 106, 7: 122, 8: 152, 10: 213, 40: 2331 };
  for (const [version, bytes] of Object.entries(known)) {
    assert.equal(byteCapacity(Number(version)), bytes, `version ${version}`);
  }
});

test("a text that is too long is refused instead of drawn wrongly", () => {
  assert.equal(versionFor(2332), null);
  assert.throws(() => encodeQr("x".repeat(2332)), RangeError);
});

test("every chosen mask gives a valid code: the same text always gives the same picture", () => {
  const text = "otpauth://totp/Test:a%40b.co?secret=ABCDEFGHIJKLMNOP";
  assert.deepEqual(encodeQr(text), encodeQr(text));
  const sizes = new Set(Array.from({ length: 8 }, (_, mask) => encodeQr(text, { mask }).length));
  assert.equal(sizes.size, 1);
});

test("the three corner squares and the timing lines are in place", () => {
  const matrix = encodeQr("hello world");
  const size = matrix.length;
  const finder = (x: number, y: number) => {
    for (let dy = 0; dy < 7; dy++)
      for (let dx = 0; dx < 7; dx++) {
        const edge = Math.max(Math.abs(dx - 3), Math.abs(dy - 3));
        assert.equal(matrix[y + dy][x + dx], edge !== 2, `finder ${x},${y} at ${dx},${dy}`);
      }
  };
  finder(0, 0);
  finder(size - 7, 0);
  finder(0, size - 7);
  for (let i = 8; i < size - 8; i++) {
    assert.equal(matrix[6][i], i % 2 === 0, "timing row");
    assert.equal(matrix[i][6], i % 2 === 0, "timing column");
  }
  assert.equal(matrix[size - 8][8], true, "the always-dark module");
});

test("text in any language is encoded as UTF-8", () => {
  assert.ok(encodeQr("தமிழ் ✓").length >= 21);
  assert.notDeepEqual(encodeQr("é"), encodeQr("e"));
});

test("the drawing path covers exactly the dark modules, plus the quiet border", () => {
  const matrix = encodeQr("hello world");
  const { path, size } = qrPath(matrix);
  assert.equal(size, matrix.length + 8);
  // redraw the path into a grid and compare it with the matrix
  const grid = Array.from({ length: size }, () => new Array<boolean>(size).fill(false));
  for (const [, x, y, width] of path.matchAll(/M(\d+) (\d+)h(\d+)v1h-\d+z/g).map((m) => m.map(Number))) {
    for (let i = 0; i < width; i++) grid[y][x + i] = true;
  }
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      const inside = y >= 4 && y < size - 4 && x >= 4 && x < size - 4;
      assert.equal(grid[y][x], inside ? matrix[y - 4][x - 4] : false, `module ${x},${y}`);
    }
});
